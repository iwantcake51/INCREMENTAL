// Extracts only the game-icons.net glyphs the game references into src/ui/icons.gen.ts.
// Icons by Lorc, Delapouite and contributors — https://game-icons.net — CC BY 3.0.
// Run with: npm run icons
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');
const OUT = 'src/ui/icons.gen.ts';

const files = [];
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.ts$/.test(f) && !p.endsWith('icons.gen.ts')) files.push(p);
  }
};
walk('src');

const resolve = (name) => set.icons[name] ?? (set.aliases?.[name] && set.icons[set.aliases[name].parent]);
const used = new Set();
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) {
    if (resolve(m[1])) used.add(m[1]);
  }
}

const entries = [...used].sort().map((name) => {
  // Each body is a single <path>; keep only the d attribute to stay compact.
  const d = [...resolve(name).body.matchAll(/ d="([^"]+)"/g)].map((x) => x[1]).join(' ');
  return `  '${name}': '${d}',`;
});

writeFileSync(
  OUT,
  `// AUTO-GENERATED by tools/build-icons.mjs — do not edit by hand.\n` +
    `// Icons from https://game-icons.net by Lorc, Delapouite and contributors, licensed CC BY 3.0.\n` +
    `export const ICON_PATHS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Wrote ${used.size} icons to ${OUT}`);
